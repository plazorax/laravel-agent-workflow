<?php

declare(strict_types=1);

/*
 * Shared helpers for the hook scripts.
 *
 * Hook contract (Claude Code hooks reference, https://code.claude.com/docs/en/hooks):
 * - the event payload arrives as one JSON object on stdin;
 * - exit 0 with a JSON object on stdout is parsed as structured output;
 * - any other non-zero exit except 2 is a non-blocking error.
 *
 * Every script here exits 0 and communicates through JSON, so a crash in a
 * helper can never be mistaken for a deliberate block.
 */

namespace LaravelAgentWorkflow;

/**
 * Read and decode the hook payload. Malformed input yields an empty array.
 *
 * @return array<string, mixed>
 */
function read_hook_input(?string $raw = null): array
{
    $raw ??= (string) stream_get_contents(STDIN);

    try {
        $decoded = json_decode($raw, true, 64, JSON_THROW_ON_ERROR);
    } catch (\JsonException) {
        return [];
    }

    if (! is_array($decoded)) {
        return [];
    }

    $input = [];
    foreach ($decoded as $key => $value) {
        if (is_string($key)) {
            $input[$key] = $value;
        }
    }

    return $input;
}

/**
 * The Laravel project root: CLAUDE_PROJECT_DIR, then the payload's cwd, then getcwd().
 *
 * @param  array<string, mixed>  $input
 */
function project_dir(array $input): string
{
    $fromEnv = getenv('CLAUDE_PROJECT_DIR');
    if (is_string($fromEnv) && $fromEnv !== '') {
        return rtrim($fromEnv, '/');
    }

    if (isset($input['cwd']) && is_string($input['cwd']) && $input['cwd'] !== '') {
        return rtrim($input['cwd'], '/');
    }

    return (string) getcwd();
}

/**
 * Pull tool_input.file_path out of a PreToolUse / PostToolUse payload.
 *
 * @param  array<string, mixed>  $input
 */
function tool_file_path(array $input): ?string
{
    $toolInput = $input['tool_input'] ?? null;
    if (! is_array($toolInput)) {
        return null;
    }

    $path = $toolInput['file_path'] ?? null;

    return is_string($path) && $path !== '' ? $path : null;
}

/**
 * Lexically normalise a path ("." and ".." segments) without touching the disk,
 * so it works for files that do not exist yet (Write creates them).
 */
function normalize_path(string $path, string $base): string
{
    if (! str_starts_with($path, '/')) {
        $path = rtrim($base, '/').'/'.$path;
    }

    $parts = [];
    foreach (explode('/', $path) as $segment) {
        if ($segment === '' || $segment === '.') {
            continue;
        }
        if ($segment === '..') {
            array_pop($parts);

            continue;
        }
        $parts[] = $segment;
    }

    return '/'.implode('/', $parts);
}

/**
 * Path of $path relative to $root, or null when it lies outside $root.
 */
function relative_to(string $path, string $root): ?string
{
    $path = normalize_path($path, $root);
    $root = normalize_path($root, '/');

    if ($path === $root) {
        return '';
    }

    $prefix = rtrim($root, '/').'/';

    return str_starts_with($path, $prefix) ? substr($path, strlen($prefix)) : null;
}

/**
 * Why an edit to $filePath must be refused, or null when it is allowed.
 *
 * Comparison is case-insensitive because the default macOS file system is.
 */
function protected_path_reason(string $filePath, string $projectDir): ?string
{
    $absolute = normalize_path($filePath, $projectDir);
    $basename = strtolower(basename($absolute));

    if ($basename === '.env' || (str_starts_with($basename, '.env.') && $basename !== '.env.example')) {
        return 'Blocked by laravel-agent-workflow: '.basename($absolute).' holds secrets and machine-specific '
            .'configuration. Do not edit it. Add new keys with safe placeholder values to .env.example and ask '
            .'the user to update their own .env.';
    }

    $relative = relative_to($absolute, $projectDir);
    if ($relative === null) {
        return null;
    }
    $relativeLower = strtolower($relative);

    if ($relativeLower === 'composer.lock') {
        return 'Blocked by laravel-agent-workflow: composer.lock is generated by Composer. Change dependencies '
            .'with `composer require`, `composer remove` or `composer update <package>` instead of editing the lock file.';
    }

    if (str_starts_with($relativeLower, 'vendor/')) {
        return 'Blocked by laravel-agent-workflow: vendor/ is managed by Composer and is overwritten on the next '
            .'install. Fix the behaviour in application code (for example by extending or binding a class in a '
            .'service provider) or upgrade the package.';
    }

    if (str_starts_with($relativeLower, 'storage/')) {
        return 'Blocked by laravel-agent-workflow: storage/ holds runtime data (logs, cache, sessions, compiled '
            .'views, uploads). Do not edit it by hand; change the code or config that produces it.';
    }

    return null;
}

/**
 * Run a command without a shell. stdout and stderr are collected into one
 * string in the order they arrive.
 *
 * @param  list<string>  $command
 * @return array{exit: int, output: string}
 */
function run_command(array $command, string $cwd, int $timeoutSeconds = 240): array
{
    $descriptors = [
        0 => ['file', '/dev/null', 'r'],
        1 => ['pipe', 'w'],
        2 => ['pipe', 'w'],
    ];

    $env = getenv();
    $env['NO_COLOR'] = '1';

    $process = @proc_open($command, $descriptors, $pipes, $cwd, $env);
    if (! is_resource($process)) {
        return ['exit' => 127, 'output' => 'Could not start: '.implode(' ', $command)];
    }

    stream_set_blocking($pipes[1], false);
    stream_set_blocking($pipes[2], false);
    $open = [$pipes[1], $pipes[2]];
    $output = '';
    $deadline = microtime(true) + $timeoutSeconds;

    while ($open !== []) {
        $read = $open;
        $write = null;
        $except = null;
        if (@stream_select($read, $write, $except, 0, 50_000) === false) {
            break;
        }
        foreach ($read as $stream) {
            $chunk = fread($stream, 65536);
            if (is_string($chunk) && $chunk !== '') {
                $output .= $chunk;
            } elseif (feof($stream)) {
                $open = array_values(array_filter($open, static fn ($s) => $s !== $stream));
            }
        }

        if (microtime(true) > $deadline) {
            proc_terminate($process);
            fclose($pipes[1]);
            fclose($pipes[2]);
            proc_close($process);

            return ['exit' => 124, 'output' => $output."\n[timed out after {$timeoutSeconds}s]"];
        }
    }

    fclose($pipes[1]);
    fclose($pipes[2]);
    $exit = proc_close($process);

    return ['exit' => $exit, 'output' => $output];
}

/**
 * Strip ANSI escapes and keep the end of the output: at most $maxLines lines and
 * about $maxChars bytes. Claude Code caps hook strings at 10,000 characters, so
 * the Stop hook (two gates) has to stay well below that.
 */
function tail_output(string $text, int $maxLines = 60, int $maxChars = 4000): string
{
    $text = (string) preg_replace('/\e\[[0-9;?]*[A-Za-z]/', '', $text);
    $lines = preg_split('/\r?\n/', trim($text)) ?: [];

    $kept = [];
    $length = 0;
    for ($i = count($lines) - 1; $i >= 0 && count($kept) < $maxLines; $i--) {
        $line = $lines[$i];
        if ($length + strlen($line) > $maxChars) {
            if ($kept === []) {
                $kept[] = '...'.substr($line, -$maxChars);
            }
            break;
        }
        $kept[] = $line;
        $length += strlen($line) + 1;
    }

    $kept = array_reverse($kept);
    $omitted = count($lines) - count($kept);
    if ($omitted > 0) {
        array_unshift($kept, "[... {$omitted} earlier lines omitted ...]");
    }

    return implode("\n", $kept);
}

/**
 * Write a JSON object to stdout for Claude Code to parse. Tool output is not
 * guaranteed to be UTF-8, so invalid bytes are substituted instead of throwing.
 *
 * @param  array<string, mixed>  $payload
 */
function emit(array $payload): void
{
    fwrite(STDOUT, json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE | JSON_THROW_ON_ERROR)."\n");
}

/**
 * Integer setting from the environment, falling back to $default when unset or invalid.
 */
function env_int(string $name, int $default): int
{
    $value = getenv($name);

    return is_string($value) && ctype_digit($value) && (int) $value > 0 ? (int) $value : $default;
}
