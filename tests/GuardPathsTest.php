<?php

declare(strict_types=1);

namespace LaravelAgentWorkflow\Tests;

use PHPUnit\Framework\Attributes\DataProvider;

final class GuardPathsTest extends HookTestCase
{
    /**
     * @return iterable<string, array{string, string}>
     */
    public static function protectedPaths(): iterable
    {
        yield '.env' => ['.env', '.env holds secrets'];
        yield '.env.local' => ['.env.local', '.env.local holds secrets'];
        yield '.env.production' => ['.env.production', 'holds secrets'];
        yield '.env.testing in subdirectory' => ['packages/demo/.env.testing', 'holds secrets'];
        yield 'composer.lock' => ['composer.lock', 'composer.lock is generated by Composer'];
        yield 'vendor file' => ['vendor/laravel/framework/src/Illuminate/Support/Str.php', 'vendor/ is managed by Composer'];
        yield 'storage log' => ['storage/logs/laravel.log', 'storage/ holds runtime data'];
        yield 'compiled view' => ['storage/framework/views/abc.php', 'storage/ holds runtime data'];
        yield 'upper-case vendor (case-insensitive FS)' => ['Vendor/foo/bar.php', 'vendor/ is managed by Composer'];
    }

    #[DataProvider('protectedPaths')]
    public function test_it_denies_edits_to_protected_paths(string $relative, string $expectedReason): void
    {
        $result = $this->runHook('guard-paths.php', $this->payload('Edit', $this->project.'/'.$relative));

        self::assertSame(0, $result['exit']);
        self::assertSame('PreToolUse', self::field($result, 'hookSpecificOutput', 'hookEventName'));
        self::assertSame('deny', self::field($result, 'hookSpecificOutput', 'permissionDecision'));
        self::assertStringContainsString($expectedReason, self::field($result, 'hookSpecificOutput', 'permissionDecisionReason'));
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function allowedPaths(): iterable
    {
        yield 'model' => ['app/Models/User.php'];
        yield '.env.example' => ['.env.example'];
        yield 'composer.json' => ['composer.json'];
        yield 'config file' => ['config/services.php'];
        yield 'nested lock file' => ['resources/js/composer.lock.md'];
        yield 'directory named like storage but not at root' => ['app/Services/storage/Disk.php'];
        yield 'blade view' => ['resources/views/welcome.blade.php'];
    }

    #[DataProvider('allowedPaths')]
    public function test_it_allows_ordinary_project_files(string $relative): void
    {
        $result = $this->runHook('guard-paths.php', $this->payload('Write', $this->project.'/'.$relative));

        self::assertSame(0, $result['exit']);
        self::assertSame('', $result['stdout']);
    }

    public function test_it_resolves_relative_paths_against_the_project(): void
    {
        $result = $this->runHook('guard-paths.php', $this->payload('Edit', 'app/../vendor/autoload.php'));

        self::assertStringContainsString('vendor/', (string) $result['stdout']);
    }

    public function test_it_ignores_files_outside_the_project_except_env_files(): void
    {
        $outside = $this->runHook('guard-paths.php', $this->payload('Edit', '/tmp/elsewhere/vendor/file.php'));
        $outsideEnv = $this->runHook('guard-paths.php', $this->payload('Edit', '/tmp/elsewhere/.env'));

        self::assertSame('', $outside['stdout']);
        self::assertStringContainsString('"permissionDecision":"deny"', $outsideEnv['stdout']);
    }

    public function test_it_falls_back_to_the_payload_cwd_without_claude_project_dir(): void
    {
        $result = $this->runHook(
            'guard-paths.php',
            ['cwd' => $this->project] + $this->payload('Edit', $this->project.'/storage/app/x.txt'),
            ['CLAUDE_PROJECT_DIR' => ''],
        );

        self::assertStringContainsString('storage/', $result['stdout']);
    }

    public function test_it_is_silent_for_payloads_without_a_file_path(): void
    {
        $bash = $this->runHook('guard-paths.php', ['hook_event_name' => 'PreToolUse', 'tool_name' => 'Bash', 'tool_input' => ['command' => 'ls']]);
        $empty = $this->runHook('guard-paths.php', []);

        self::assertSame([0, ''], [$bash['exit'], $bash['stdout']]);
        self::assertSame([0, ''], [$empty['exit'], $empty['stdout']]);
    }

    /**
     * @return array<string, mixed>
     */
    private function payload(string $tool, string $filePath): array
    {
        return [
            'session_id' => 'test',
            'hook_event_name' => 'PreToolUse',
            'tool_name' => $tool,
            'tool_input' => ['file_path' => $filePath, 'content' => '<?php'],
        ];
    }
}
